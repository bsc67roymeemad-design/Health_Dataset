// Helper to parse CSV cleanly
function parseCSV(text: string): HealthRecord[] {
  const lines = text.trim().split('\n').filter(l => l.trim().length > 0);
  if (lines.length < 2) return [];

  const parseLine = (line: string): string[] => {
    const res: string[] = [];
    let cur = '';
    let inQuotes = false;
    for (let i = 0; i < line.length; i++) {
      const c = line[i];
      if (c === '"') {
        if (inQuotes && line[i + 1] === '"') {
          cur += '"';
          i++;
        } else {
          inQuotes = !inQuotes;
        }
      } else if (c === ',' && !inQuotes) {
        res.push(cur.trim());
        cur = '';
      } else {
        cur += c;
      }
    }
    res.push(cur.trim());
    return res;
  };

  const headers = parseLine(lines[0]);
  const records: HealthRecord[] = [];

  for (let i = 1; i < lines.length; i++) {
    const row = parseLine(lines[i]);
    if (!row[0] || row[0] === '') continue;
    const map: Record<string, string> = {};
    headers.forEach((h, idx) => {
      if (h) map[h] = row[idx] || '';
    });

    if (map['รหัสบุคคล']) {
      records.push({
        id: map['รหัสบุคคล'] || `H00${i}`,
        screenDate: map['วันที่คัดกรอง'] || '',
        area: map['พื้นที่'] || '',
        gender: map['เพศ'] || '',
        age: Number(map['อายุ']) || 0,
        heightCm: Number(map['ส่วนสูง_cm']) || 0,
        weightKg: Number(map['น้ำหนัก_kg']) || 0,
        bmi: Number(map['BMI']) || 0,
        sbp: Number(map['SBP_mmHg']) || 0,
        dbp: Number(map['DBP_mmHg']) || 0,
        pulse: Number(map['ชีพจร_bpm']) || 0,
        bloodSugar: Number(map['น้ำตาล_mg_dL']) || 0,
        smoking: map['สูบบุหรี่'] || 'ไม่สูบ',
        alcohol: map['ดื่มแอลกอฮอล์'] || 'ไม่ดื่ม',
        exercise: map['การออกกำลังกาย'] || 'บางครั้ง',
        diabetesRisk: map['เบาหวาน_คัดกรอง'] || 'ไม่มี',
        hypertensionRisk: map['ความดันโลหิตสูง_คัดกรอง'] || 'ไม่มี',
        riskScore: Number(map['คะแนนความเสี่ยง']) || 0,
        riskLevel: map['ระดับความเสี่ยง'] || 'ต่ำ',
        month: map['เดือน'] || ''
      });
    }
  }

  return records;
}

