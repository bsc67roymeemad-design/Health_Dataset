export async function fetchSheetData(): Promise<{ records: HealthRecord[]; isLive: boolean; updatedTime: string }> {
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 6000);
    const response = await fetch(SHEET_DATA_URL, {
      signal: controller.signal,
      cache: 'no-cache'
    });
    clearTimeout(timeoutId);

    if (!response.ok) {
      throw new Error(`HTTP error ${response.status}`);
    }

    const csvText = await response.text();
    const parsed = parseCSV(csvText);
    if (parsed.length > 0) {
      return {
        records: parsed,
        isLive: true,
        updatedTime: new Date().toLocaleTimeString('th-TH', { hour: '2-digit', minute: '2-digit', second: '2-digit' }) + ' น.'
      };
    }
  } catch {
    // Graceful fallback to verified initial records
  }

  return {
    records: INITIAL_HEALTH_RECORDS,
    isLive: false,
    updatedTime: '31 มีนาคม 2026 (16:30 น.)'
  };
}
